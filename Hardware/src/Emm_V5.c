/******************************************************
Function:    		void StepperMotorControl_init_location(StepperMotorControl_location *control, uint8_t address) 
Description: 		指定电机初始化函数（这个函数是用来指定电机的位置的）
Calls:				 	NONE 
Input: 					StepperMotorControl_location *control这个变量是结构体变量，这个结构体里面有3个成员
								分别对应了当前发送的数据，上次发送的数据，以及当前的位置值
								address	是电机设定的地址
******************************************************/

void StepperMotorControl_init_location(StepperMotorControl_location *control, uint8_t address) 
{
	
	
    uint8_t defaultBytes[13] = {0x00, 0xFD, 0x00, 0x00, 0xaf,0x00,0x00,0x00,0x00,0x00,0x01,0x00,0x6B};
    memcpy(control->controlBytes, defaultBytes, 13);
    memcpy(control->lastControlBytes, defaultBytes, 13);
    control->controlBytes[0] = address;
}


/******************************************************
Function:    		void StepperMotorset_pos(UART_HandleTypeDef *huart,StepperMotorControl_location *control, uint8_t direction, uint16_t speed1, uint32_t angle) 
Description: 		指定电机位置（这个函数是用来指定电机的位置的）
Calls:				 	NONE 
Input: 					UART_HandleTypeDef串口号
								StepperMotorControl_location *control这个变量是结构体变量，确定电机地址
								direction表示方向
								speed1表示速度
								angle表示角度
******************************************************/
void StepperMotorset_pos(UART_HandleTypeDef *huart,StepperMotorControl_location *control, uint8_t direction, uint16_t speed1, uint32_t angle) {
  
    uint8_t addr = control->controlBytes[0];

 
    if (speed1 == 0) {
        Emm_V5_Stop_Now(huart, addr, 0);
        return;
    }

  
    uint16_t rpm_speed= speed1;
		uint32_t a_clk = angle * 3200 / 360;

		Emm_V5_Pos_Control(huart, addr, direction, rpm_speed, 0, a_clk, 1, 0);

}

